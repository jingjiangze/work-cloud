def pick(pool, index: int) -> str:
    """按序号取内容；序号超出库容量时循环取用，避免重复堆积在最后一篇"""
    if not pool:
        return ""
    return pool[(index - 1) % len(pool)]


def generate_local(title: str, count: int = 500) -> str:
    """根据标题生成报告正文（本地内容库版，不调用任何外部 AI）"""
    import re

    idx = 1
    m = re.search(r"第\s*(\d+)\s*[周月]", title or "")
    if m:
        idx = max(1, int(m.group(1)))

    if "周报" in (title or ""):
        return pick(WEEKLY, idx)
    if "月报" in (title or ""):
        return pick(MONTHLY, idx)
    # 日报等未预设的类型，退回周报库取一篇通用内容
    return pick(WEEKLY, idx)
